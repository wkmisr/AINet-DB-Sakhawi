#!/usr/bin/env python3
"""wdgn_by_generator.py — 下書きの wd/gn 誤りを、生成したアプリの版ごとに数える。

目的(2026-11-18): v20.12(2026-10-26)でプロンプト RULE 0b と wd/gn 検疫を入れた効果を測る。
校閲者の修正記録 FIXLOG(assertion_type = wd_ref / gn_ref)を、各項目の初版コメント
「generated by AINet-DB Researcher Pro vXX」の版で分け、100 項目あたりの件数を出す。
v20.12 以降で生成した下書きが校閲に回ったら、このスクリプトを再実行して比べる。
quarantine_wd_gn_xml.py を後掛けした下書きは、FIXLOG の description か ISSUES にその旨を残す。

使い方: python3 docs/tools/wdgn_by_generator.py [--types wd_ref,gn_ref]
"""
import argparse, glob, os, re, collections as C
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ap = argparse.ArgumentParser(); ap.add_argument("--types", default="wd_ref,gn_ref"); a = ap.parse_args()
types = set(a.types.split(","))
ver = {}
for f in glob.glob(os.path.join(REPO, "Individuals", "**", "*.xml"), recursive=True):
    s = open(f, encoding="utf-8").read(3000)
    m = re.search(r'xml:id="([^"]+)"', s); g = re.search(r"generated by AINet-DB Researcher Pro (v[\d.]+)", s)
    if m: ver[m.group(1)] = g.group(1) if g else "unknown"
def era(v):
    try: n = tuple(int(x) for x in v[1:].split("."))
    except Exception: return "unknown"
    return "v20.12 以降" if n >= (20, 12) else "v20.11.1 以前"
fixes = C.Counter()
for f in sorted(glob.glob(os.path.join(REPO, "docs", "batches", "*", "FIXLOG*.tsv"))):
    for l in open(f, encoding="utf-8"):
        p = l.rstrip("\n").split("\t")
        if len(p) < 4 or p[3] not in ("FP", "FN", "substitution"): continue
        if p[2] in types: fixes[(p[0], era(ver.get(p[1], "unknown")))] += 1
# 分母 = FIXLOG に1行以上ある項目(ほぼ全項目に修正があるため、セットの項目数とほぼ一致)
batch_entries = C.Counter()
for d in glob.glob(os.path.join(REPO, "docs", "batches", "*", "")):
    b = os.path.basename(os.path.dirname(d))
    ids = set()
    for f in glob.glob(os.path.join(d, "FIXLOG*.tsv")):
        ids.update(l.split("\t")[1] for l in open(f, encoding="utf-8") if l.count("\t") > 3)
    for i in ids: batch_entries[(b, era(ver.get(i, "unknown")))] += 1
print("batch\tera\tentries(with fixes)\twd/gn fixes\tper 100 entries")
tot = C.Counter(); totn = C.Counter()
for k in sorted(set(fixes) | set(batch_entries), key=lambda k: (int(re.search(r"\d+", k[0]).group()), k[1])):
    n = batch_entries[k]; x = fixes[k]; tot[k[1]] += x; totn[k[1]] += n
    print(f"{k[0]}\t{k[1]}\t{n}\t{x}\t{100*x/n:.1f}" if n else f"{k[0]}\t{k[1]}\t0\t{x}\t-")
for e in tot: print(f"TOTAL\t{e}\t{totn[e]}\t{tot[e]}\t{100*tot[e]/totn[e]:.1f}")

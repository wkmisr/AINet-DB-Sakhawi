OVR = {O(314): 'ADM', O(365): 'ADM', O(37): 'ADM', O(386): 'REL', O(396): 'ADM', O(348): 'ADM', O(89): 'ADM',
       O(23): 'MIL', O(310): 'REL', O(195): 'JUD', O(275): 'SRV', O(86): 'ADM', O(157): 'ADM', O(241): 'ADM',
       O(344): 'ADM', O(168): 'ADM', O(244): 'ADM', O(132): 'MIL', O(398): 'ADM', O(299): 'OCC', O(269): 'REL',
       O(218): 'OCC', O(193): 'OCC', O(239): 'OCC'}
out = []
for k in order + list(WD):
    a = im[k][0] if k in im else WD[k]
    act, tgt = 'keep', ''
    if k in MERGE: act, tgt = 'merge', MERGE[k]
    elif k in COLLAPSE: act, tgt = 'collapse', COLLAPSE[k]
    elif k in RETIRE: act, tgt = 'retire', ''
    new = RENAME.get(k, '')
    out.append(dict(id=k, arabic=a, uses=use[k], category=CAT[OVR.get(k) or cat(k, new or a)], action=act, target=tgt,
                    rename=new, note=RETIRE.get(k, '')))
json.dump(out, open(W + 'office_actions.json', 'w'), ensure_ascii=False)
c = collections.Counter(o['action'] for o in out); print(c)
print('records affected by merge/collapse', sum(o['uses'] for o in out if o['action'] in ('merge', 'collapse')))
print(collections.Counter(o['category'] for o in out if o['action'] == 'keep'))
for o in out:
    if o['category'] in ('OCC',) and o['action'] == 'keep': print('OCC', o['id'], o['arabic'], o['uses'])

import csv, json, re, collections, sys

W = '/home/claude/work/'
im, order = {}, []
for r in csv.reader(open(W + 'idmaster.tsv', encoding='utf-8'), delimiter='\t'):
    if len(r) > 4 and r[4].startswith('TMP-O-') and r[4] not in im:
        im[r[4]] = (r[2], r[5] if len(r) > 5 else '')
        order.append(r[4])
rows = json.load(open(W + 'states.json'))
use = collections.Counter(r[2].lstrip('#') for r in rows)
WD = {k: l for k, l in [('wd:Q217029', 'قاض'), ('wd:Q215536', 'تاجر'), ('wd:Q932945', 'خطيب'), ('wd:Q125482', 'الإمامة'),
      ('wd:Q3595924', 'مقرئ'), ('wd:Q2892720', 'صوفي'), ('wd:Q239718', 'مؤذن'), ('wd:Q352842', 'تدريس'),
      ('wd:Q7492880', 'مشيخة (شيخ)'), ('wd:Q242468', 'الخياط'), ('wd:Q175240', 'وزير'), ('wd:Q43292', 'سلطان'),
      ('wd:Q12227702', 'الموقت'), ('wd:Q5612976', 'مجذوب')]}

